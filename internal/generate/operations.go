package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/token"
	"maps"
	"slices"
	"strings"
)

func (g *generator) methods() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go generate; DO NOT EDIT.\n\npackage sourcecraft\n\nimport (\"context\"; \"encoding/json\"; \"fmt\"; \"net/http\"; \"net/url\"; \"strconv\"; \"time\")")

	seen := map[string]bool{}

	for _, path := range slices.Sorted(maps.Keys(g.spec.Paths)) {
		for _, method := range slices.Sorted(maps.Keys(g.spec.Paths[path])) {
			g.method(&b, path, method, seen)
		}
	}

	return b.Bytes()
}

func (g *generator) queryOptions(b *bytes.Buffer, op operation, params []parameter) {
	name := op.ID + "Options"
	comment(b, name+" contains query parameters for "+op.ID+".")
	fmt.Fprintf(b, "type %s struct {\n", name)

	for _, p := range params {
		g.queryOptionField(b, op, p)
	}

	fmt.Fprintln(b, "}")
	fmt.Fprintf(b, "func (o *%s) queryValues() (url.Values, error) {\nq := make(url.Values)\nif o == nil {\n", name)

	required := false

	for _, p := range params {
		if p.Required {
			required = true
		}
	}

	if required {
		fmt.Fprintf(b, "return nil, fmt.Errorf(%q)\n", "sourcecraft: options are required for "+op.ID)
	} else {
		fmt.Fprintln(b, "return q, nil")
	}

	fmt.Fprintln(b, "}")

	for _, p := range params {
		writePlatformQueryValue(b, op, p)
	}

	fmt.Fprintln(b, "return q, nil\n}")
}

func (g *generator) method(b *bytes.Buffer, path, method string, seen map[string]bool) {
	if !slices.Contains([]string{"get", "post", "put", "patch", "delete", "head", "options"}, method) {
		panic("unsupported path item: " + method)
	}

	op := g.spec.Paths[path][method]
	if op.ID == "" || seen[op.ID] {
		panic("missing or duplicate operation ID: " + op.ID)
	}

	if !token.IsIdentifier(op.ID) || !ast.IsExported(op.ID) {
		panic("operation ID is not an exported Go identifier: " + op.ID)
	}

	seen[op.ID] = true

	pathParams, queryParams, body := platformParameters(op)

	if len(queryParams) > 0 {
		g.queryOptions(b, op, queryParams)
	}

	resultType := g.platformResponseType(op)

	form := g.methodSignature(b, path, method, op, pathParams, queryParams, body, resultType)

	errorReturn := platformRequestChecks(b, op, body, form, resultType)

	fmt.Fprintf(b, "path, err := expandPath(%q", path)

	for _, p := range pathParams {
		fmt.Fprintf(b, ", pathParam{%q, %s}", p.Name, variableName(p.Name))
	}

	fmt.Fprintln(b, ")")
	fmt.Fprintf(b, "if err != nil { %s }\n", errorReturn)

	g.methodCall(b, op, method, queryParams, body, form, resultType)

	fmt.Fprint(b, "}\n\n")
}

func platformParameters(op operation) ([]parameter, []parameter, *parameter) {
	var (
		pathParams, queryParams []parameter
		body                    *parameter
	)

	for i, p := range op.Parameters {
		switch p.In {
		case namePath:
			pathParams = append(pathParams, p)
		case "query":
			queryParams = append(queryParams, p)
		case nameBody:
			if body != nil {
				panic("multiple bodies for " + op.ID)
			}

			body = &op.Parameters[i]
		default:
			panic("unsupported parameter location: " + p.In)
		}
	}

	return pathParams, queryParams, body
}

func (g *generator) platformResponseType(op operation) string {
	var responseSchema *schema

	hasSuccess := false

	for _, status := range slices.Sorted(maps.Keys(op.Responses)) {
		if strings.HasPrefix(status, "2") {
			if hasSuccess {
				panic("multiple success responses for " + op.ID)
			}

			hasSuccess = true
			responseSchema = op.Responses[status].Schema
		}
	}

	if !hasSuccess {
		panic("missing success response for " + op.ID)
	}

	resultType := ""

	if responseSchema != nil {
		g.rejectQuotedInteger(responseSchema)
		resultType = g.goType(responseSchema)
	}

	return resultType
}

func (g *generator) methodSignature(b *bytes.Buffer, path, method string, op operation, pathParams, queryParams []parameter, body *parameter, resultType string) *schema {
	comment(b, op.ID+" calls "+strings.ToUpper(method)+" "+path+".")

	if op.Summary != "" {
		comment(b, op.Summary+".")
	}

	if slices.Contains(op.Tags, "Withdrawn") {
		comment(b, "Deprecated: this endpoint is listed as Withdrawn in the API specification.")
	}

	fmt.Fprintf(b, "func (c *Client) %s(ctx context.Context", op.ID)

	for _, p := range pathParams {
		if p.Type != typeString {
			panic("non-string path parameter: " + op.ID)
		}

		fmt.Fprintf(b, ", %s string", variableName(p.Name))
	}

	if body != nil {
		g.rejectQuotedInteger(body.Schema)
		fmt.Fprintf(b, ", body *%s", g.inputType(body.Schema))
	}

	var form *schema

	if op.RequestBody != nil {
		if len(op.RequestBody.Content) != 1 {
			panic("unsupported request body: " + op.ID)
		}

		content, ok := op.RequestBody.Content["multipart/form-data"]
		if !ok {
			panic("unsupported request media type: " + op.ID)
		}

		form = content.Schema
		rejectPlatformComposition(form)

		if form.Properties[nameFile] == nil {
			panic("missing multipart file: " + op.ID)
		}

		for _, field := range slices.Sorted(maps.Keys(form.Properties)) {
			rejectPlatformComposition(form.Properties[field])

			if field != nameFile {
				if form.Properties[field].Type != typeString {
					panic("unsupported multipart field: " + field)
				}

				fmt.Fprintf(b, ", %s string", variableName(field))
			}
		}

		fmt.Fprint(b, ", file *Upload")
	}

	if len(queryParams) > 0 {
		fmt.Fprintf(b, ", opts *%sOptions", op.ID)
	}

	if resultType == "" {
		fmt.Fprintln(b, ") (*Response, error) {")
	} else {
		fmt.Fprintf(b, ") (*%s, *Response, error) {\n", resultType)
	}

	return form
}

func platformRequestChecks(b *bytes.Buffer, op operation, body *parameter, form *schema, resultType string) string {
	errorReturn := "return nil, nil, err"
	if resultType == "" {
		errorReturn = "return nil, err"
	}

	if body != nil && body.Required {
		fmt.Fprintf(b, "if body == nil { err := fmt.Errorf(%q); %s }\n", "sourcecraft: body is required for "+op.ID, errorReturn)
	}

	if form != nil {
		for _, field := range slices.Sorted(maps.Keys(form.Properties)) {
			if field != nameFile && slices.Contains(form.Required, field) {
				fmt.Fprintf(b, "if %s == \"\" { err := fmt.Errorf(%q); %s }\n", variableName(field), "sourcecraft: multipart field "+field+" is required", errorReturn)
			}
		}
	}

	return errorReturn
}

func (g *generator) methodCall(b *bytes.Buffer, op operation, method string, queryParams []parameter, body *parameter, form *schema, resultType string) {
	options, bodyArg := exprNil, exprNil
	if len(queryParams) > 0 {
		options = "opts"
	}

	if body != nil {
		bodyArg = nameBody

		if !body.Required {
			fmt.Fprintln(b, "var requestBody any\nif body != nil { requestBody = body }")

			bodyArg = nameRequestBody
		}
	}

	methodName := "http.Method" + strings.ToUpper(method[:1]) + method[1:]

	if form != nil {
		if resultType == "" {
			panic("multipart without a typed response: " + op.ID)
		}

		fmt.Fprintf(b, "return doUpload[%s](ctx, c, %s, path, %s, file, []formField{", resultType, methodName, options)

		for _, field := range slices.Sorted(maps.Keys(form.Properties)) {
			if field != nameFile {
				fmt.Fprintf(b, "{%q, %s},", field, variableName(field))
			}
		}

		fmt.Fprintln(b, "})")
	} else if resultType == "" {
		fmt.Fprintf(b, "return doEmpty(ctx, c, %s, path, %s, %s)\n", methodName, options, bodyArg)
	} else {
		fmt.Fprintf(b, "return doJSON[%s](ctx, c, %s, path, %s, %s)\n", resultType, methodName, options, bodyArg)
	}
}

func (g *generator) queryOptionField(b *bytes.Buffer, op operation, p parameter) {
	if p.Description != "" {
		comment(b, p.Description)
	}

	if p.Required {
		comment(b, "Required.")
	}

	typ := g.goType(&schema{Type: p.Type, Format: p.Format, Items: p.Items})
	switch typ {
	case typeString, typeInt32, typeInt64, typeUint64, typeBool, "[]string":
	default:
		panic("unsupported query type for " + op.ID + ": " + typ)
	}

	if p.Type == typeBoolean && !p.Required {
		typ = "*bool"
	}

	fmt.Fprintf(b, "%s %s\n", goName(p.Name), typ)
}

func writePlatformQueryValue(b *bytes.Buffer, op operation, p parameter) {
	field := "o." + goName(p.Name)
	if p.Required && p.Type == typeString && p.Format != typeInt64 && p.Format != typeUint64 {
		fmt.Fprintf(b, "if %s == \"\" { return nil, fmt.Errorf(%q) }\n", field, "sourcecraft: query parameter "+p.Name+" is required")
	}

	switch p.Type {
	case typeBoolean:
		if p.Required {
			fmt.Fprintf(b, "q.Set(%q, strconv.FormatBool(%s))\n", p.Name, field)
		} else {
			fmt.Fprintf(b, "if %s != nil { q.Set(%q, strconv.FormatBool(*%s)) }\n", field, p.Name, field)
		}
	case typeString, typeInteger:
		value, condition := field, field+" != \"\""
		if p.Format == typeUint64 {
			value = "strconv.FormatUint(" + field + ", 10)"
			condition = field + " != 0"
		} else if p.Format == typeInt64 || p.Type == typeInteger {
			integer := field
			if p.Format == typeInt32 {
				integer = "int64(" + field + ")"
			}

			value = "strconv.FormatInt(" + integer + ", 10)"
			condition = field + " != 0"
		}

		if p.Required {
			fmt.Fprintf(b, "q.Set(%q, %s)\n", p.Name, value)
		} else {
			fmt.Fprintf(b, "if %s { q.Set(%q, %s) }\n", condition, p.Name, value)
		}
	case typeArray:
		if p.CollectionFormat != "multi" || p.Items == nil || p.Items.Type != typeString {
			panic("unsupported query array: " + op.ID)
		}

		fmt.Fprintf(b, "for _, value := range %s { q.Add(%q, value) }\n", field, p.Name)
	default:
		panic("unsupported query parameter: " + op.ID + ": " + p.Type)
	}
}
