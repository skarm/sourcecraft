package main

import (
	"bytes"
	"fmt"
	"maps"
	"slices"
)

func (g *generator) models() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go generate; DO NOT EDIT.\n\npackage sourcecraft\n\nimport (\"encoding/json\"; \"time\")")

	usedNames := map[string]bool{}

	for _, name := range slices.Sorted(maps.Keys(g.spec.Definitions)) {
		s := g.spec.Definitions[name]

		typeName := goName(name)
		if usedNames[typeName] {
			panic("duplicate model name: " + typeName)
		}

		usedNames[typeName] = true

		description := s.Description
		if description == "" {
			description = s.Title
		}

		if description == "" {
			description = "is the API model for " + name + "."
		}

		comment(&b, typeName+" "+description)

		if len(s.Enum) > 0 {
			fmt.Fprintf(&b, "type %s string\n\nconst (\n", typeName)

			for _, value := range s.Enum {
				constant := typeName + goName(value)
				if usedNames[constant] {
					panic("duplicate enum constant: " + constant)
				}

				usedNames[constant] = true
				fmt.Fprintf(&b, "%s %s = %q\n", constant, typeName, value)
			}

			fmt.Fprintln(&b, ")")

			continue
		}

		if s.Type != typeObject || s.AdditionalProperties != nil {
			panic("unsupported definition: " + name)
		}

		g.objectModel(&b, typeName, s, g.pointerOptionals[name], false)
	}

	for _, name := range slices.Sorted(maps.Keys(g.projections)) {
		typeName := goName(name) + "Input"
		if usedNames[typeName] {
			panic("input projection name collides with an existing declaration: " + typeName)
		}

		usedNames[typeName] = true
		comment(&b, typeName+" is the request projection of "+goName(name)+".")
		g.objectModel(&b, typeName, g.spec.Definitions[name], true, true)
	}

	return b.Bytes()
}

func (g *generator) objectModel(b *bytes.Buffer, typeName string, s *schema, pointerOptionals, input bool) {
	fmt.Fprintf(b, "type %s struct {\n", typeName)

	fieldNames := map[string]bool{}

	for _, field := range slices.Sorted(maps.Keys(s.Properties)) {
		property := s.Properties[field]

		fieldName := goName(field)
		if fieldNames[fieldName] {
			panic("duplicate field name in " + typeName + ": " + fieldName)
		}

		fieldNames[fieldName] = true

		description := property.Description
		if description == "" {
			description = property.Title
		}

		if description != "" {
			comment(b, description)
		}

		required := slices.Contains(s.Required, field)

		fieldType := g.goType(property)
		if input {
			fieldType = g.inputType(property)
		}

		if g.needsPointer(property, pointerOptionals, required) {
			fieldType = "*" + fieldType
		}

		tag := jsonFieldName(field)

		resolved := g.resolve(property)
		if resolved.Type == typeString && (resolved.Format == typeInt64 || resolved.Format == typeUint64) {
			tag += ",string"
		}

		if !required {
			tag += ",omitzero"
		}

		if tag == "-" {
			tag += ","
		}

		fmt.Fprintf(b, "%s %s `json:%q`\n", fieldName, fieldType, tag)
	}

	fmt.Fprint(b, "}\n\n")
}
